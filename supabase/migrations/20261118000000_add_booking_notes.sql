-- =====================================================================
--  Booking notes shared by ttmsabot-personalworkschedule and
--  ttmsabot-workschedule
--
--  Purpose:
--    Staff (therapist / queue staff) can record a note on a booking
--    without deleting or changing the booking itself. The note is
--    visible in both apps so the queue team knows about changes such
--    as "the patient called to cancel but did not cancel in the app".
--
--  Run this in Supabase Dashboard > SQL Editor (or via Supabase CLI).
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1) One current note per booking
-- ---------------------------------------------------------------------
create table if not exists public.booking_notes (
  id bigint generated by default as identity primary key,
  booking_id text not null,
  booking_date date not null,
  booking_time time without time zone not null,
  therapist_name text not null,
  note text not null,
  updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint booking_notes_booking_id_key unique (booking_id)
);

comment on table public.booking_notes is
  'Staff notes attached to a booking. Adding/editing a note must never delete or modify the booking itself.';
comment on column public.booking_notes.booking_id is
  'bookings.booking_id of the booking this note belongs to';
comment on column public.booking_notes.note is
  'Latest note shown to staff in personalworkschedule and workschedule';
comment on column public.booking_notes.updated_by is
  'Full name of the staff member who last saved the note';

create index if not exists booking_notes_booking_date_idx
  on public.booking_notes (booking_date);

create index if not exists booking_notes_therapist_date_idx
  on public.booking_notes (therapist_name, booking_date);

-- ---------------------------------------------------------------------
-- 2) Keep updated_at accurate even when a note is edited via SQL
-- ---------------------------------------------------------------------
create or replace function public.touch_booking_notes_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists booking_notes_set_updated_at on public.booking_notes;
create trigger booking_notes_set_updated_at
  before update on public.booking_notes
  for each row execute function public.touch_booking_notes_updated_at();

-- ---------------------------------------------------------------------
-- 3) Access: only staff apps that are signed in may read/write notes.
--    The patient portal does not use this table.
-- ---------------------------------------------------------------------
alter table public.booking_notes enable row level security;

grant select, insert, update, delete on public.booking_notes to authenticated;

drop policy if exists "booking_notes_staff_access" on public.booking_notes;
create policy "booking_notes_staff_access"
  on public.booking_notes
  for all
  to authenticated
  using (
    public.has_app_access('personalworkschedule')
    or public.has_app_access('workschedule')
  )
  with check (
    public.has_app_access('personalworkschedule')
    or public.has_app_access('workschedule')
  );

commit;

-- ให้ PostgREST เห็นตารางใหม่ทันที
notify pgrst, 'reload schema';

